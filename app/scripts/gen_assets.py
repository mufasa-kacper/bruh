# Regenerates src/assets.ts from the processed images in assets/img (sizes read from the files).
import os
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), '..')
IMG = os.path.join(ROOT, 'assets/img')

def size(p):
    with Image.open(p) as im:
        return im.size

L = ['// Generated by scripts/gen_assets.py: maps painted assets to require() calls and their pixel sizes.', '/* eslint-disable */',
     'export type Sized = { src: number; w: number; h: number };',
     'export type PoseAsset = { frames: number[]; w: number; h: number; head: number[] };', '']
import json
L.append('export const CHARS: Record<string, Record<string, PoseAsset>> = {')
for hero in sorted(os.listdir(f'{IMG}/chars')):
    meta = json.load(open(f'{IMG}/chars/{hero}/meta.json'))
    L.append(f'  {hero}: {{')
    for p, m in meta.items():
        fr = ', '.join(f"require('../assets/img/chars/{hero}/{p}_{k}.webp')" for k in range(3))
        L.append(f"    {p}: {{ frames: [{fr}], w: {m['w']}, h: {m['h']}, head: [{m['head'][0]}, {m['head'][1]}] }},")
    L.append('  },')
L.append('};\n')
for name, sub in [('FURN', 'furniture'), ('UI', 'ui'), ('TEX', 'tex'), ('SCENES', 'scenes')]:
    L.append(f'export const {name} = {{')
    for fn in sorted(os.listdir(f'{IMG}/{sub}')):
        k, ext = os.path.splitext(fn)
        w, h = size(f'{IMG}/{sub}/{fn}')
        L.append(f"  {k}: {{ src: require('../assets/img/{sub}/{fn}'), w: {w}, h: {h} }},")
    L.append('};\n')
L.append('export type FurnName = keyof typeof FURN;')
L.append('export type UIName = keyof typeof UI;')
open(os.path.join(ROOT, 'src/assets.ts'), 'w').write('\n'.join(L) + '\n')
print('ok')
